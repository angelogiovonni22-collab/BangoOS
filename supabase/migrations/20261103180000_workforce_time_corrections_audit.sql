begin;

-- Keep every correction and review append-only; do not rewrite historic payroll.
create table public.workforce_time_audit (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  time_entry_id uuid not null,
  action text not null check (action in ('corrected','resubmitted','approved','rejected')),
  actor_id uuid not null,
  reason text not null,
  before_data jsonb not null,
  after_data jsonb not null,
  created_at timestamptz not null default now(),
  foreign key (time_entry_id,company_id)
    references public.workforce_time_entries(id,company_id) on delete restrict
);
create index workforce_time_audit_entry_idx
  on public.workforce_time_audit(company_id,time_entry_id,created_at desc);

alter table public.workforce_time_audit enable row level security;
revoke all on public.workforce_time_audit from public,anon,authenticated;
grant select,insert on public.workforce_time_audit to authenticated;
create policy workforce_time_audit_read
  on public.workforce_time_audit for select to authenticated
  using (public.has_company_role(company_id,
    array['owner','administrator','operations_manager','project_manager','superintendent','foreman','office_manager']));
-- INSERTs are generated by the audit trigger, never directly from the application.
create policy workforce_time_audit_trigger_insert
  on public.workforce_time_audit for insert to authenticated
  with check (pg_trigger_depth()>0 and public.has_company_role(company_id,
    array['owner','administrator','operations_manager','project_manager','superintendent','foreman','office_manager'])
    and actor_id=auth.uid());

create function public.guard_workforce_time_payroll_history()
returns trigger language plpgsql security invoker set search_path=pg_catalog as $$
begin
  -- Time identity, job allocation and original location evidence cannot change
  -- as a side effect of approval or a manager's correction.
  if old.status in ('submitted','rejected') and
     (new.id,new.company_id,new.employee_id,new.project_id,new.assignment_id,
      new.created_by,new.created_at,new.clock_in_location,new.clock_out_location,new.source)
     is distinct from
     (old.id,old.company_id,old.employee_id,old.project_id,old.assignment_id,
      old.created_by,old.created_at,old.clock_in_location,old.clock_out_location,old.source) then
    raise exception 'Time entry identity, project and original clock evidence cannot be rewritten';
  end if;
  if old.status='rejected' and new.status not in ('rejected','submitted') then
    raise exception 'Rejected time must be corrected and resubmitted before approval';
  end if;
  if old.status='submitted' and new.status not in ('submitted','approved','rejected') then
    raise exception 'Submitted time transition is not allowed';
  end if;
  if old.status='submitted' and new.status in ('approved','rejected') and
    (new.started_at,new.ended_at,new.break_minutes,new.notes)
    is distinct from (old.started_at,old.ended_at,old.break_minutes,old.notes) then
    raise exception 'Review cannot silently change hours or notes; correct time first';
  end if;
  if old.status='approved' or exists(
    select 1 from public.payroll_time_entry_claims c
     where c.company_id=old.company_id and c.time_entry_id=old.id
  ) then
    if new is distinct from old then
      raise exception 'Approved or payroll-claimed time is immutable; use payroll recovery instead';
    end if;
  end if;
  return new;
end $$;
revoke all on function public.guard_workforce_time_payroll_history() from public,anon,authenticated;
create trigger workforce_time_payroll_history_guard
before update on public.workforce_time_entries
for each row execute function public.guard_workforce_time_payroll_history();

create function public.audit_workforce_time_changes()
returns trigger language plpgsql security invoker set search_path=pg_catalog as $$
declare v_action text;v_reason text;
begin
  if old is not distinct from new or old.status not in ('submitted','rejected') then
    return new;
  end if;
  if new.status='approved' then v_action:='approved';
  elsif new.status='rejected' then v_action:='rejected';
  elsif old.status='rejected' and new.status='submitted' then v_action:='resubmitted';
  else v_action:='corrected'; end if;

  v_reason:=nullif(btrim(current_setting('app.workforce_time_correction_reason',true)),'');
  if v_reason is null then
    v_reason:=case when v_action in ('approved','rejected') then 'Manager time review' else 'Manager time correction' end;
  end if;
  insert into public.workforce_time_audit(
    company_id,time_entry_id,action,actor_id,reason,before_data,after_data)
  values(old.company_id,old.id,v_action,auth.uid(),v_reason,
    to_jsonb(old),to_jsonb(new));
  return new;
end $$;
revoke all on function public.audit_workforce_time_changes() from public,anon,authenticated;
create trigger workforce_time_audit_on_update
after update on public.workforce_time_entries
for each row execute function public.audit_workforce_time_changes();

-- The previously installed assignment guard must also revalidate when a
-- correction moves time to another crew-membership calendar date.
drop trigger workforce_time_assignment_link_guard on public.workforce_time_entries;
create trigger workforce_time_assignment_link_guard
before insert or update of company_id,employee_id,project_id,assignment_id,started_at
on public.workforce_time_entries
for each row execute function public.guard_workforce_time_assignment_link();

create function public.correct_workforce_time_entry(
 p_company_id uuid,p_entry_id uuid,p_started_at timestamptz,p_ended_at timestamptz,
 p_break_minutes integer,p_notes text,p_reason text
) returns public.workforce_time_entries
language plpgsql security invoker set search_path=pg_catalog as $$
declare v_entry public.workforce_time_entries;
begin
  if not public.has_company_role(p_company_id,
    array['owner','administrator','operations_manager','project_manager','superintendent','foreman','office_manager'])
  then raise exception 'Not authorized to correct workforce time'; end if;
  if length(btrim(coalesce(p_reason,'')))<5 then
    raise exception 'A correction reason of at least five characters is required'; end if;
  if p_started_at is null or p_ended_at is null or p_ended_at<=p_started_at then
    raise exception 'Clock-out must be after clock-in'; end if;
  if p_break_minutes is null or p_break_minutes<0 or p_break_minutes>1440
    or p_break_minutes>=extract(epoch from (p_ended_at-p_started_at))/60 then
    raise exception 'Break minutes must be less than the shift duration'; end if;
  if p_ended_at>now()+interval '5 minutes' then
    raise exception 'Corrected clock-out cannot be in the future'; end if;

  -- Set a transaction-local reason for the append-only trigger; failed updates
  -- roll back both the time correction and its audit entry.
  perform set_config('app.workforce_time_correction_reason',btrim(p_reason),true);
  update public.workforce_time_entries
     set started_at=p_started_at,ended_at=p_ended_at,
         break_minutes=p_break_minutes,notes=nullif(btrim(p_notes),''),
         status='submitted',approved_by=null,approved_at=null,updated_at=now()
   where id=p_entry_id and company_id=p_company_id
     and status in ('submitted','rejected')
     and not exists(select 1 from public.payroll_time_entry_claims c
                    where c.company_id=p_company_id and c.time_entry_id=p_entry_id)
   returning * into v_entry;
  if not found then raise exception 'Time entry is not correctable; refresh to see its status'; end if;
  return v_entry;
end $$;
revoke all on function public.correct_workforce_time_entry(uuid,uuid,timestamptz,timestamptz,integer,text,text)
from public,anon,authenticated;
grant execute on function public.correct_workforce_time_entry(uuid,uuid,timestamptz,timestamptz,integer,text,text)
to authenticated;
commit;
