// Runs the real clock component with isolated React and service boundaries.
import assert from "node:assert/strict";
import { readFile,writeFile,mkdtemp,rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve,join,dirname,basename } from "node:path";
import { pathToFileURL } from "node:url";
import * as runtime from "./workforce-clock-test-runtime.mjs";
const loaded=await import(pathToFileURL(resolve(process.argv[2])).href),ts=loaded.default||loaded;
const scratch=await mkdtemp(join(tmpdir(),"bos-clock-state-"));
const oldWindow=Object.getOwnPropertyDescriptor(globalThis,"window"),oldNavigator=Object.getOwnPropertyDescriptor(globalThis,"navigator"),oldNow=Date.now;
let now=Date.parse("2026-11-04T13:00:00Z"),timerId=0,checks=0;
const timers=new Map();
Date.now=()=>now;
Object.defineProperty(globalThis,"window",{configurable:true,value:{setInterval(callback){const id=++timerId;timers.set(id,callback);return id;},clearInterval(id){timers.delete(id);}}});
Object.defineProperty(globalThis,"navigator",{configurable:true,value:{geolocation:{getCurrentPosition(_success,error){error({code:1});}}}});
const check=(value,label)=>{assert.ok(value,label);checks++;};
const text=node=>node==null?"":typeof node==="string"?node:Array.isArray(node)?node.map(text).join(""):text(node.props?.children);
function find(node,predicate){if(!node||typeof node!=="object")return null;if(Array.isArray(node)){for(const child of node){const found=find(child,predicate);if(found)return found;}return null;}if(predicate(node))return node;return find(node.props?.children,predicate);}
const button=(app,label)=>find(app.tree,node=>node.type==="button"&&text(node)===label);
const select=app=>find(app.tree,node=>node.props?.["aria-label"]==="Employee time clock");
const timer=app=>find(app.tree,node=>node.props?.role==="timer");
let app;
try{
 const transpile=source=>ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX}}).outputText;
 const helperPath=join(scratch,"helper.mjs");await writeFile(helperPath,transpile(await readFile("lib/crews/workforce-clock-state.ts","utf8")));
 const stubUrl=pathToFileURL(resolve("scripts/workforce-clock-test-runtime.mjs")).href,helperUrl=pathToFileURL(helperPath).href;
 let source=transpile(await readFile("components/crews/mobile-workforce-time-clock.tsx","utf8"));
 source=source.replace(/(["'])(?:react(?:\/jsx-runtime)?|lucide-react|@\/components\/ui|@\/lib\/crews\/workforce-time)\1/g,JSON.stringify(stubUrl))
  .replace(/(["'])@\/lib\/crews\/workforce-clock-state\1/g,JSON.stringify(helperUrl));
 const componentPath=join(scratch,"component.mjs");await writeFile(componentPath,source);
 const {MobileWorkforceTimeClock:Component}=await import(pathToFileURL(componentPath).href);
 const props={employees:[{id:"a",name:"Synthetic A"},{id:"b",name:"Synthetic B"}],projectId:"synthetic-project",assignmentId:"synthetic-assignment"};
 app=runtime.createRenderer(Component,props);
 check(button(app,"Clock in").props.disabled,"wait for authoritative status before enabling writes");
 await app.settle();
 check(!button(app,"Clock in").props.disabled,"no saved shift enables clock-in");
 check(button(app,"Clock out").props.disabled,"no open shift disables clock-out");
 const release=runtime.holdRecord();
 button(app,"Clock in").props.onClick();await app.settle();
 check(button(app,"Clock in").props.disabled,"pending action is protected from duplicate clicks");
 check(!button(app,"Clocked in"),"clock state never changes optimistically before save");
 release();await app.settle();
 check(button(app,"Clocked in").props.style.backgroundColor.includes("success"),"confirmed clock-in is green");
 check(button(app,"Clocked in").props.disabled,"confirmed in state disables duplicate clock-in");
 check(!button(app,"Clock out").props.disabled,"confirmed open shift enables clock-out");
 check(timers.size===1,"open shift starts one live timer");
 now+=65000;for(const tick of timers.values())tick();await app.settle();
 check(text(timer(app))==="00:01:05","live timer uses saved start and current time");
 check(text(app.tree).includes("denied or blocked"),"location failure is explained instead of silently omitted");
 app.unmount();check(timers.size===0,"unmount releases the live timer");
 app=runtime.createRenderer(Component,props);await app.settle();
 check(Boolean(button(app,"Clocked in")),"remount restores persisted in state");
 check(text(timer(app))==="00:01:05","remount does not restart elapsed time from zero");
 select(app).props.onChange({target:{value:"b"}});app.render();await app.settle();
 check(!button(app,"Clocked in")&&!timer(app),"another employee does not inherit state or timer");
 check(timers.size===0,"switching away stops the previous employee timer");
 const releaseRead=runtime.holdRead("a");
 select(app).props.onChange({target:{value:"a"}});app.render();
 select(app).props.onChange({target:{value:"b"}});app.render();await app.settle();
 releaseRead();await app.settle();
 check(!button(app,"Clocked in"),"late previous-employee response cannot overwrite current state");
 select(app).props.onChange({target:{value:"a"}});app.render();await app.settle();
 now=Date.parse("2026-11-04T13:02:05Z");
 find(app.tree,node=>node.props?.["aria-label"]==="Break minutes").props.onChange({target:{value:"1"}});app.render();
 button(app,"Clock out").props.onClick();await app.settle();
 check(button(app,"Clocked out").props.style.backgroundColor.includes("danger"),"confirmed clock-out is red");
 check(button(app,"Clocked out").props.disabled,"duplicate clock-out is disabled");
 check(text(timer(app))==="00:01:05","closed worked time subtracts one unpaid minute");
 check(timers.size===0,"closed shift stops ticking");
 now+=3600000;app.render();check(text(timer(app))==="00:01:05","closed total stays fixed as real time advances");
 app.unmount();app=runtime.createRenderer(Component,props);await app.settle();
 check(Boolean(button(app,"Clocked out"))&&text(timer(app))==="00:01:05","reload restores red state and final worked total");
 runtime.failRecord();button(app,"Clock in").props.onClick();await app.settle();
 check(!button(app,"Clocked in")&&Boolean(button(app,"Clocked out")),"failed save never flips into a successful in state");
 check(text(app.tree).includes("Synthetic save rejected"),"failed save remains visible");
 app.unmount();runtime.setReadFailure(true);app=runtime.createRenderer(Component,props);await app.settle();
 check(button(app,"Clock in").props.disabled&&button(app,"Clock out").props.disabled,"read failure fails closed for clock actions");
 check(Boolean(button(app,"Retry clock status")),"read failure offers a retry");
 runtime.setReadFailure(false);button(app,"Retry clock status").props.onClick();await app.settle();
 check(Boolean(button(app,"Clocked out")),"retry recovers the saved state");
 console.log("Workforce clock component: "+checks+" isolated behavior assertions passed.");
}finally{
 app?.unmount();Date.now=oldNow;
 if(oldWindow)Object.defineProperty(globalThis,"window",oldWindow);else Reflect.deleteProperty(globalThis,"window");
 if(oldNavigator)Object.defineProperty(globalThis,"navigator",oldNavigator);else Reflect.deleteProperty(globalThis,"navigator");
 if (dirname(resolve(scratch)) !== resolve(tmpdir()) || !basename(scratch).startsWith("bos-clock-state-")) throw new Error("Unexpected temporary path");
 await rm(scratch,{recursive:true,force:true});
}
