// Isolated PostgreSQL regression. No production credentials or connections.
import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { pathToFileURL } from "node:url";
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
const migrations = await readdir("supabase/migrations");
const readMigration = async (suffix) => {
  const matches = migrations.filter((name) => name.endsWith(suffix));
  assert.equal(matches.length, 1);
  return readFile("supabase/migrations/" + matches[0], "utf8");
};
const guard = await readMigration("_profile_access_write_guard.sql");
const membershipGuard = await readMigration("_company_membership_write_guard.sql");
const foundation = await readFile("supabase/migrations/20260729170000_multi_company_foundation.sql", "utf8");
const sync = foundation.match(/create or replace function public\.trg_company_memberships_sync_profiles_fn\(\)[\s\S]*?\$\$;/i)?.[0];
const hasRole = foundation.match(/create or replace function public\.has_company_role\([\s\S]*?\$\$;/i)?.[0];
assert.ok(sync && hasRole);
const db = new PGlite();
const A="00000000-0000-4000-8000-000000000001", B="00000000-0000-4000-8000-000000000002", C="00000000-0000-4000-8000-000000000003";
const owner="00000000-0000-4000-8000-000000000101", employee="00000000-0000-4000-8000-000000000102", inactive="00000000-0000-4000-8000-000000000103", newcomer="00000000-0000-4000-8000-000000000104", invited="00000000-0000-4000-8000-000000000105";
let checks=0;
const q=async (sql,values=[]) => (await db.query(sql,values)).rows;
const as=async (uid,role="authenticated") => {
  await db.exec("reset role; set role "+role);
  await q("select set_config('request.jwt.claim.sub',$1,false)",[uid||""]);
};
const root=async()=>db.exec("reset role");
const denied=async(sql,label)=>{ await assert.rejects(db.exec(sql),e=>e.code==="42501",label); checks++; };
try {
  await db.exec(`
    create role authenticated; create role anon; create role service_role bypassrls;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create table companies(id uuid primary key,owner_id uuid not null);
    create table profiles(id uuid primary key,company_id uuid references companies(id),role text not null default 'member',first_name text,last_name text,phone text,created_at timestamptz default now(),updated_at timestamptz default now());
    create table company_memberships(id uuid primary key default gen_random_uuid(),company_id uuid not null references companies(id),user_id uuid not null,role text not null,status text not null default 'active',is_primary boolean default false,joined_at timestamptz default now(),created_at timestamptz default now(),updated_at timestamptz default now(),unique(company_id,user_id));
    create function company_role_weight(text) returns int language sql as $$select case when $1='owner' then 10 else 0 end$$;
    insert into companies values('${A}','${owner}'),('${B}','00000000-0000-4000-8000-000000000199');
    insert into profiles(id,company_id,role) values('${owner}','${A}','owner'),('${employee}','${A}','employee'),('${inactive}',null,'employee');
    insert into company_memberships(company_id,user_id,role,status,is_primary) values('${A}','${owner}','owner','active',true),('${A}','${employee}','employee','active',true),('${A}','${inactive}','employee','inactive',false);
    grant usage on schema auth,public to authenticated,anon,service_role;
    grant select,insert,update on profiles to authenticated;
    grant insert on profiles to anon;
    grant select,insert,update,delete on company_memberships to authenticated;
    grant select,insert on companies to authenticated;
    grant all on profiles,companies,company_memberships to service_role;
    alter table profiles enable row level security;
    alter table companies enable row level security;
    alter table company_memberships enable row level security;
    create policy profiles_select_own_profile on profiles for select to authenticated using(id=auth.uid());
    create policy profiles_insert_own_profile on profiles for insert to authenticated with check(id=auth.uid());
    create policy profiles_update_own_profile on profiles for update to authenticated using(id=auth.uid()) with check(id=auth.uid());
    create policy company_read on companies for select to authenticated using(owner_id=auth.uid() or exists(select 1 from company_memberships cm where cm.company_id=id and cm.user_id=auth.uid() and cm.status='active'));
    create policy company_insert on companies for insert to authenticated with check(owner_id=auth.uid());
    create policy membership_read on company_memberships for select to authenticated using(user_id=auth.uid());
    create policy membership_insert on company_memberships for insert to authenticated with check(user_id=auth.uid());
    create policy membership_update on company_memberships for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
  `);
  await db.exec(hasRole+"\n"+sync);
  await db.exec("create trigger membership_sync after insert or update or delete on company_memberships for each row execute function trg_company_memberships_sync_profiles_fn()");
  await db.exec(membershipGuard);
  await as(employee);
  await db.exec(`update profiles set company_id='${B}',role='owner' where id='${employee}'`);
  assert.equal((await q("select role from profiles"))[0].role,"owner","legacy own-row update can forge profile access"); checks++;
  await root();
  await db.exec(`update profiles set company_id='${A}',role='employee' where id='${employee}'`);
  await db.exec(guard);
  await as(employee);
  await denied(`update profiles set role='owner' where id='${employee}'`,"cannot promote profile role");
  await denied(`update profiles set company_id='${B}' where id='${employee}'`,"cannot attach foreign company");
  await denied(`update profiles set company_id='${B}',role='owner' where id='${employee}'`,"cannot forge foreign owner");
  await db.exec(`update profiles set first_name='Synthetic',phone='synthetic-only' where id='${employee}'`);
  assert.equal((await q("select first_name from profiles"))[0].first_name,"Synthetic","normal personal fields remain editable"); checks++;
  await db.exec(`update profiles set company_id=null where id='${employee}'`);
  await denied(`update profiles set role='owner' where id='${employee}'`,"detaching company cannot promote role");
  await db.exec(`update profiles set company_id='${A}',role='employee' where id='${employee}'`);
  assert.equal((await q("select company_id from profiles"))[0].company_id,A,"verified membership restores profile mirror"); checks++;
  await as(inactive);
  await denied(`update profiles set company_id='${A}' where id='${inactive}'`,"inactive membership cannot restore company link");
  await as(newcomer);
  await denied(`insert into profiles(id,role) values('${newcomer}','owner')`,"new user cannot seed an elevated role");
  await db.exec(`insert into profiles(id,first_name) values('${newcomer}','New synthetic owner')`);
  assert.equal((await q("select role from profiles"))[0].role,"member","neutral owner-setup profile seed uses actual default"); checks++;
  await db.exec(`insert into companies values('${C}','${newcomer}')`);
  await db.exec(`insert into profiles(id,company_id,role) values('${newcomer}','${C}','owner') on conflict(id) do update set company_id=excluded.company_id,role=excluded.role`);
  assert.equal((await q("select role from profiles"))[0].role,"owner","actual owner can complete onboarding before membership"); checks++;
  await db.exec(`insert into company_memberships(company_id,user_id,role,is_primary) values('${C}','${newcomer}','owner',true)`);
  assert.equal((await q("select company_id from profiles"))[0].company_id,C,"membership synchronization remains compatible"); checks++;
  await as(null,"service_role");
  await db.exec(`insert into profiles(id,company_id,role) values('${invited}','${A}','foreman')`);
  assert.equal((await q(`select role from profiles where id='${invited}'`))[0].role,"foreman","trusted invitation backend remains available"); checks++;
  await root();
  await db.exec(`update company_memberships set role='foreman' where user_id='${employee}'`);
  assert.equal((await q(`select role from profiles where id='${employee}'`))[0].role,"foreman","trusted membership role synchronization remains available"); checks++;
  await db.exec(`update company_memberships set status='inactive' where user_id='${employee}'`);
  assert.equal((await q(`select company_id from profiles where id='${employee}'`))[0].company_id,null,"membership revocation clears profile mirror"); checks++;
  await as(employee);
  await denied(`update profiles set company_id='${A}',role='foreman' where id='${employee}'`,"revoked user cannot undo profile synchronization");
  await as(null,"anon");
  await denied(`insert into profiles(id) values('00000000-0000-4000-8000-000000000999')`,"anonymous profile insert denied");
  await root();
  await db.exec(guard);
  const fn=(await q("select prosecdef,has_function_privilege('authenticated',oid,'EXECUTE') as callable from pg_proc where oid='public.guard_profile_access_writes()'::regprocedure"))[0];
  assert.equal(fn.prosecdef,false); assert.equal(fn.callable,false); checks+=2;
  assert.equal((await q("select count(*)::int as total from pg_trigger where tgrelid='public.profiles'::regclass and tgname='trg_profiles_guard_access_writes'"))[0].total,1); checks++;
  console.log("Profile access write guard: "+checks+" isolated PostgreSQL assertions passed.");
} finally { await db.close(); }
