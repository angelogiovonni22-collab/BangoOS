import assert from "node:assert/strict";
import { createEmptyMobileDailyReportDraft } from "./mobile-field-operations-types";
import { appendReportPhoto, removeReportPhoto, reportPhotoAttachments } from "./mobile-report-photos";
const original = {...createEmptyMobileDailyReportDraft(),photos:["legacy.png"]};
const first = appendReportPhoto(original,{id:"photo-a",fileName:"same.png"});
assert.deepEqual(original.photos,["legacy.png"]);
assert.deepEqual(first.photoIds,[null,"photo-a"]);
const second = appendReportPhoto(first,{id:"photo-b",fileName:"same.png"});
assert.deepEqual(second.photoIds,[null,"photo-a","photo-b"]);
assert.deepEqual(second.photos,["legacy.png","same.png","same.png"]);
const removed = removeReportPhoto(second,1);
assert.deepEqual(removed.photos,["legacy.png","same.png"]);
assert.deepEqual(removed.photoIds,[null,"photo-b"]);
assert.deepEqual(second.photoIds,[null,"photo-a","photo-b"]);
const restored = JSON.parse(JSON.stringify(removed));
assert.deepEqual(restored.photoIds,[null,"photo-b"]);
const saved = reportPhotoAttachments(restored,"2026-11-05T14:00:00Z");
assert.equal(saved[0].projectPhotoId,undefined);
assert.equal(saved[1].projectPhotoId,"photo-b");
assert.equal(saved[1].fileName,"same.png");
assert.equal(saved[1].uploadedAt,"2026-11-05T14:00:00Z");
assert.ok(!("url" in saved[1]),"short-lived signed URLs are not persisted into reports");
assert.deepEqual(removeReportPhoto(original,0).photoIds,[]);
assert.equal(appendReportPhoto(first,{id:"photo-a",fileName:"same.png"}), first, "recovered upload handoff does not append the same photo twice");
assert.deepEqual(appendReportPhoto(second,{id:"photo-b",fileName:"same.png"}).photoIds,[null,"photo-a","photo-b"]);
console.log("Mobile report photo identity: 16 assertions passed.");
