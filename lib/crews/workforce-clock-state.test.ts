import assert from "node:assert/strict";
import { parseWorkforceClockEntry, workforceWorkedSeconds, formatWorkforceDuration, workforceLocationFailure } from "./workforce-clock-state";
const row = { id: "synthetic", status: "open", started_at: "2026-11-04T13:00:00Z", ended_at: null, break_minutes: 0 };
const active = parseWorkforceClockEntry(row)!;
assert.ok(active);
assert.equal(active.endedAt, null);
assert.equal(formatWorkforceDuration(workforceWorkedSeconds(active, Date.parse("2026-11-04T14:02:03Z"))), "01:02:03");
assert.equal(formatWorkforceDuration(workforceWorkedSeconds(active, Date.parse("2026-11-04T12:59:00Z"))), "00:00:00", "device clock behind the start never displays negative work");
const closed = parseWorkforceClockEntry({ ...row, status: "submitted", ended_at: "2026-11-04T21:30:00Z", break_minutes: 30 })!;
assert.equal(formatWorkforceDuration(workforceWorkedSeconds(closed, Date.parse("2026-11-05T01:00:00Z"))), "08:00:00", "closed work subtracts the recorded unpaid break");
assert.equal(workforceWorkedSeconds(closed, 0), workforceWorkedSeconds(closed, Date.now()), "closed total does not keep ticking");
assert.equal(formatWorkforceDuration(25 * 3600 + 7), "25:00:07", "long shifts do not wrap at midnight");
assert.equal(parseWorkforceClockEntry({ ...row, started_at: "bad" }), null);
assert.equal(parseWorkforceClockEntry({ ...row, ended_at: "bad" }), null);
assert.equal(parseWorkforceClockEntry({ ...row, status: "submitted" }), null);
assert.equal(parseWorkforceClockEntry({ ...row, break_minutes: -1 }), null);
assert.equal(parseWorkforceClockEntry(null), null);
assert.match(workforceLocationFailure(1), /denied or blocked/);
assert.match(workforceLocationFailure(2), /could not determine/);
assert.match(workforceLocationFailure(3), /timed out/);
assert.match(workforceLocationFailure(), /unavailable/);
console.log("Workforce clock duration and location states: 16 assertions passed.");
